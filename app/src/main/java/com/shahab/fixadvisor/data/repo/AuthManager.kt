package com.shahab.fixadvisor.data.repo

import android.content.Context
import android.content.Intent
import com.google.android.gms.auth.api.signin.GoogleSignIn
import com.google.android.gms.auth.api.signin.GoogleSignInOptions
import com.google.android.gms.common.api.ApiException
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.auth.FirebaseUser
import com.google.firebase.auth.GoogleAuthProvider
import com.google.firebase.auth.ktx.auth
import com.google.firebase.ktx.Firebase
import com.shahab.fixadvisor.R
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asStateFlow
import kotlinx.coroutines.tasks.await

/**
 * Google Sign-In backed by Firebase Auth.
 *
 * Browsing shops is anonymous and needs no account. Sign-in is REQUIRED for
 * writing reviews, registering a shop, replying to reviews and favourites —
 * the security rules (see README.md) reject those writes without auth.
 * No tokens are stored by us; Firebase Auth manages the session.
 */
class AuthManager(private val context: Context) {

    private val appContext = context.applicationContext
    private val auth: FirebaseAuth = Firebase.auth

    private val _authState = MutableStateFlow(auth.currentUser)
    /** Emits the current Firebase user, or null when signed out. */
    val authState: StateFlow<FirebaseUser?> = _authState.asStateFlow()

    val currentUid: String? get() = auth.currentUser?.uid
    val isSignedIn: Boolean get() = auth.currentUser != null

    init {
        auth.addAuthStateListener { firebaseAuth ->
            _authState.value = firebaseAuth.currentUser
        }
    }

    private fun googleSignInClient() =
        GoogleSignIn.getClient(
            appContext,
            GoogleSignInOptions.Builder(GoogleSignInOptions.DEFAULT_SIGN_IN)
                // Generated by the google-services Gradle plugin from google-services.json.
                // With the placeholder file this exists but sign-in fails until replaced.
                .requestIdToken(appContext.getString(R.string.default_web_client_id))
                .requestEmail()
                .build()
        )

    /** Intent to launch via ActivityResultContracts.StartActivityForResult(). */
    fun getSignInIntent(): Intent = googleSignInClient().signInIntent

    /**
     * Completes sign-in from the activity result. Returns the Firebase user
     * on success, or the failure (user cancelled, no network, bad config…).
     */
    suspend fun handleSignInResult(data: Intent?): Result<FirebaseUser> {
        if (data == null) return Result.failure(IllegalStateException("Sign-in was cancelled."))
        val account = try {
            GoogleSignIn.getSignedInAccountFromIntent(data).getResult(ApiException::class.java)
        } catch (e: ApiException) {
            return Result.failure(e)
        }
        val idToken = account.idToken
            ?: return Result.failure(IllegalStateException("Google sign-in returned no ID token."))
        val credential = GoogleAuthProvider.getCredential(idToken, null)
        return try {
            val result = auth.signInWithCredential(credential).await()
            val user = result.user
                ?: return Result.failure(IllegalStateException("Firebase sign-in returned no user."))
            Result.success(user)
        } catch (e: Exception) {
            Result.failure(e)
        }
    }

    /** Signs out of Firebase and Google. Public data (shops, reviews) stays readable. */
    suspend fun signOut() {
        try {
            googleSignInClient().signOut().await()
        } catch (e: Exception) {
            // Best effort; Firebase sign-out below is what matters.
        }
        auth.signOut()
    }
}
